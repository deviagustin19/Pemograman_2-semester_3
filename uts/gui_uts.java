    private Mahasiswa ambilDataMahasiswa() {

        String nama = jTextField1.getText();
        String ttl = jTextField2.getText();
        String nim = jTextField3.getText();
        String prodi = jTextField4.getText();

        String fakultas = jComboBox3.getSelectedItem().toString();
        String semester = jComboBox1.getSelectedItem().toString();
        String agama = jComboBox2.getSelectedItem().toString();

        String alamat = jTextArea1.getText();
        String visiMisi = jTextArea3.getText();

        String jenisKelamin;
        if (jCheckBox1.isSelected()) {
            jenisKelamin = "Laki-laki";
        } else if (jCheckBox2.isSelected()) {
            jenisKelamin = "Perempuan";
        } else {
            jenisKelamin = "-";
        }

        return new Mahasiswa(
                nama, ttl, nim, prodi,
                fakultas, semester,
                alamat, visiMisi,
                jenisKelamin, agama
        );
    }
