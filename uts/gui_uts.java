    private void hapusDataMahasiswa() {
        int konfirmasi = JOptionPane.showConfirmDialog(
                this,
                "Yakin hapus semua data?",
                "Hapus Data",
                JOptionPane.YES_NO_OPTION
        );

        if (konfirmasi == JOptionPane.YES_OPTION) {
            try {
                new java.io.FileWriter("data_mahasiswa.txt", false).close();
                JOptionPane.showMessageDialog(this,
                        "Data berhasil dihapus",
                        "Sukses",
                        JOptionPane.INFORMATION_MESSAGE);
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this,
                        "Gagal menghapus data",
                        "Error",
                        JOptionPane.ERROR_MESSAGE);
            }
        }
    }
    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try {
            Mahasiswa mhs = ambilDataMahasiswa();

            java.io.FileWriter fw = new java.io.FileWriter("data_mahasiswa.txt", true);
            fw.write(mhs.tampilkanData());
            fw.close();

            JOptionPane.showMessageDialog(this,
                    "Data berhasil disimpan ke file!",
                    "Sukses",
                    JOptionPane.INFORMATION_MESSAGE);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Terjadi kesalahan saat menyimpan data",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

